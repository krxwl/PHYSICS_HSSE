def validate_parameters(m, R, mu, alpha_deg, beta):
    """Проверка физической допустимости входных параметров."""
    if m <= 0:
        raise ValueError(f"Масса должна быть положительной (получено m={m}).")
    if R <= 0:
        raise ValueError(f"Радиус должен быть положительным (получено R={R}).")
    if mu < 0:
        raise ValueError(f"Коэффициент трения не может быть отрицательным (получено mu={mu}).")
    if not (0.0 <= alpha_deg < 90.0):
        raise ValueError(f"Угол наклона должен быть в пределах [0, 90) градусов (получено {alpha_deg}).")
    if not (0.0 < beta <= 1.0):
        raise ValueError(f"Коэффициент момента инерции beta должен быть в (0, 1] (получено {beta}).")


