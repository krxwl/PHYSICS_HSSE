# Ограничения на параметры модели
# 1. Масса тела m > 0, радиус тела R > 0.
# 2. Коэффициент сухого трения скольжения mu >= 0.
# 3. Угол наклона плоскости alpha в диапазоне [0, 90) градусов.
# 4. Поверхность и тело считаются абсолютно твёрдыми (трением качения пренебрегаем).
# 5. Движение плоское: вектор угловой скорости перпендикулярен плоскости движения.
def validate_parameters(m, R, mu, alpha_deg, beta):
    """Проверка физической допустимости входных параметров."""
    if not all(isfinite(float(value)) for value in (m, R, mu, alpha_deg, beta)):
        raise ValueError("Все физические параметры должны быть конечными числами.")
    if m <= 0:
        raise ValueError(f"Масса должна быть положительной (получено m={m}).")
    if R <= 0:
        raise ValueError(f"Радиус должен быть положительным (получено R={R}).")
    if mu < 0:
        raise ValueError(
            f"Коэффициент трения не может быть отрицательным (получено mu={mu})."
        )
    if not (0.0 <= alpha_deg < 90.0):
        raise ValueError(
            f"Угол наклона должен быть в пределах [0, 90) градусов (получено {alpha_deg})."
        )
    if not (0.0 < beta <= 1.0):
        raise ValueError(
            f"Коэффициент момента инерции beta должен быть в (0, 1] (получено {beta})."
        )


